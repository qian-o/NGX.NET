using System.Globalization;
using System.Numerics;
using System.Security;
using System.Text;
using System.Text.Json;

namespace Streamline.NET.Generator;

internal sealed partial class CSharpEmitter(InterfaceSnapshot snapshot, TypeMapper mapper, string outputDirectory)
{
    private const string OwnershipMarker = "// Generated by Streamline.NET.Generator. Changes belong in the generator.";

    private static readonly UTF8Encoding utf8Bom = new(true);

    private readonly Dictionary<string, StringBuilder> files = new(StringComparer.Ordinal);

    private readonly Dictionary<string, (int BodyStart, string Feature)> nestedFiles = new(StringComparer.Ordinal);

    private readonly Dictionary<string, string> implementations = new(StringComparer.Ordinal);

    private readonly List<string> unhandled = [];

    private StringBuilder File(string group, string name)
    {
        string path = Path.Combine(group, name + ".g.cs");

        if (!files.TryGetValue(path, out StringBuilder? builder))
        {
            builder = new();
            builder.AppendLine("// <auto-generated/>");
            builder.AppendLine(OwnershipMarker);
            builder.AppendLine($"// Source: {snapshot.Source.Repository} {snapshot.Source.Release} ({snapshot.Source.Commit}).");
            builder.AppendLine();
            builder.AppendLine("using System.Runtime.CompilerServices;");
            builder.AppendLine("using System.Runtime.InteropServices;");
            builder.AppendLine();
            builder.AppendLine("namespace Streamline.NET;");
            if (name.StartsWith("SL.", StringComparison.Ordinal) || name == "SLNative")
            {
                builder.AppendLine();
                builder.AppendLine(name == "SLNative" ? "internal static unsafe partial class SLNative" : "public static unsafe partial class SL");
                builder.AppendLine("{");
                if (featureGroups.Contains(group) && name is "SL.Functions" or "SL.Strings" or "SL.Presets" or "SL.Flags")
                {
                    nestedFiles.Add(path, (builder.Length, group));
                }
            }
            files.Add(path, builder);
        }

        return builder;
    }

    private void Record(NativeDeclaration declaration, string implementation)
    {
        implementations[declaration.Id] = implementation;
    }

    private static void Comment(StringBuilder builder, NativeDeclaration declaration, string indent = "", string? extraRemarks = null)
    {
        string comment = declaration.Comment;

        if (comment.Length == 0)
        {
            comment = declaration.QualifiedName;
        }

        builder.AppendLine(indent + "/// <summary>");

        foreach (string line in comment.Split('\n'))
        {
            string text = line.Trim().TrimStart('/', '*', '!').TrimEnd('*', '/').Trim();
            builder.AppendLine(indent + "///" + (text.Length == 0 ? "" : " " + SecurityElement.Escape(text)));
        }

        builder.AppendLine(indent + "/// </summary>");
        builder.AppendLine(indent + $"/// <remarks>Source: {declaration.File}:{declaration.Line}. {SecurityElement.Escape(extraRemarks)}</remarks>");

        if (declaration.Deprecated)
        {
            builder.AppendLine(indent + "[Obsolete(" + JsonSerializer.Serialize(declaration.DeprecationMessage ?? "Deprecated by Streamline; see the source documentation.") + ")]");
        }
    }

    private void EmitEnum(NativeDeclaration declaration, StringBuilder? destination = null, string indent = "")
    {
        StringBuilder builder = destination ?? File(TypeMapper.Group(declaration), "Enums");
        string typeName = TypeMapper.TypeName(declaration.Name);
        string underlying = mapper.Map(declaration.UnderlyingType
            ?? throw new InvalidDataException($"Missing enum underlying type: {declaration.QualifiedName}"));
        builder.AppendLine();
        Comment(builder, declaration, indent);
        if (declaration.Flags)
        {
            builder.AppendLine(indent + "[Flags]");
        }
        builder.AppendLine($"{indent}public enum {typeName} : {underlying}");
        builder.AppendLine(indent + "{");

        foreach (NativeDeclaration member in declaration.Children.Where(child => child.Kind == "ENUM_CONSTANT_DECL"))
        {
            Comment(builder, member, indent + "    ");
            builder.AppendLine($"{indent}    {TypeMapper.EnumMember(member.Name)} = {IntegerValue(member.Value!, underlying)},");
            builder.AppendLine();
            Record(member, TypeMapper.TypeName(declaration.QualifiedName) + "." + TypeMapper.EnumMember(member.Name));
        }

        builder.AppendLine(indent + "}");
        Record(declaration, TypeMapper.TypeName(declaration.QualifiedName));
    }

    private static string IntegerValue(string value, string type)
    {
        BigInteger number = BigInteger.Parse(value, CultureInfo.InvariantCulture);

        if (number < 0 && type is "byte" or "ushort" or "uint" or "ulong")
        {
            int bits = type switch { "byte" => 8, "ushort" => 16, "uint" => 32, _ => 64 };
            number += BigInteger.One << bits;
        }

        return number.ToString(CultureInfo.InvariantCulture) + (type == "ulong" ? "UL" : type == "long" ? "L" : "");
    }

    private string ConstantValue(NativeExpression expression, NativeType nativeType)
    {
        string type = mapper.Map(nativeType);

        if (expression.Value is not null)
        {
            if (type == "float")
            {
                float value = float.Parse(expression.Value, CultureInfo.InvariantCulture);
                return value == float.MaxValue ? "float.MaxValue" : value.ToString("R", CultureInfo.InvariantCulture) + "f";
            }

            if (type == "double")
            {
                return double.Parse(expression.Value, CultureInfo.InvariantCulture).ToString("R", CultureInfo.InvariantCulture) + "d";
            }

            if (nativeType.Kind == "ENUM")
            {
                return "(" + type + ")" + expression.Value;
            }

            if (type == "Bool8")
            {
                return expression.Value == "0" ? "false" : "true";
            }

            return IntegerValue(expression.Value, type);
        }

        if (expression.Children.Count == 1)
        {
            return ConstantValue(expression.Children[0], nativeType);
        }

        throw new InvalidDataException($"Unevaluated constant: {expression.Text}");
    }

    private void EmitConstant(NativeDeclaration declaration)
    {
        if (declaration.Expressions.Count == 0)
        {
            throw new InvalidDataException($"Missing constant value: {declaration.QualifiedName}");
        }

        StringBuilder builder = File(TypeMapper.Group(declaration), "SL.Constants");
        string name = TypeMapper.ConstantName(declaration.Name);
        string type = mapper.Map(declaration.Type);
        string value = ConstantValue(declaration.Expressions[^1], declaration.Type);
        builder.AppendLine();
        Comment(builder, declaration, "    ");
        builder.AppendLine($"    public const {type} {name} = {value};");
        Record(declaration, "SL." + name);
    }

    private void WriteFiles()
    {
        foreach ((string relativePath, StringBuilder builder) in files.OrderBy(pair => pair.Key, StringComparer.Ordinal))
        {
            string path = Path.Combine(outputDirectory, relativePath);
            string text = builder.ToString();
            if (nestedFiles.TryGetValue(relativePath, out (int BodyStart, string Feature) nested))
            {
                string body = text[nested.BodyStart..].Replace("\r\n", "\n", StringComparison.Ordinal);
                string declaration = Path.GetFileName(relativePath) == "SL.Functions.g.cs"
                    ? $"    /// <summary>Streamline {nested.Feature} feature operations.</summary>\n"
                    : "";
                text = text[..nested.BodyStart] + "\n" + declaration
                    + $"    public static unsafe partial class {nested.Feature}\n    {{\n"
                    + string.Join('\n', body.Split('\n').Select(line => line.Length == 0 ? "" : "    " + line))
                    + "    }\n";
            }
            text = text.Replace("\r\n", "\n", StringComparison.Ordinal);
            string fileName = Path.GetFileName(relativePath);
            if (fileName.StartsWith("SL.", StringComparison.Ordinal) || fileName == "SLNative.g.cs")
            {
                text += "}\n";
            }
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            byte[] content = [.. utf8Bom.GetPreamble(), .. utf8Bom.GetBytes(text)];

            if (!System.IO.File.Exists(path) || !System.IO.File.ReadAllBytes(path).AsSpan().SequenceEqual(content))
            {
                System.IO.File.WriteAllBytes(path, content);
                Console.WriteLine("Updated " + relativePath);
            }
        }

        foreach (string path in Directory.EnumerateFiles(outputDirectory, "*.g.cs", SearchOption.AllDirectories))
        {
            string relativePath = Path.GetRelativePath(outputDirectory, path);

            if (!relativePath.StartsWith("obj" + Path.DirectorySeparatorChar, StringComparison.Ordinal)
                && !files.ContainsKey(relativePath) && System.IO.File.ReadAllText(path).Contains(OwnershipMarker, StringComparison.Ordinal))
            {
                System.IO.File.Delete(path);
                Console.WriteLine("Removed " + relativePath);
            }
        }
    }
}
